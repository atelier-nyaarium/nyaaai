/** Rust validator issue table. */
function issuesRust(): string {
	const entries = Object.entries(ISSUE_MESSAGES);
	const arms = (text: (code: string, template: string) => string) =>
		entries.map(([code, template]) => `Self::${pascal(code)} => ${text(code, template)},`).join("\n");
	return `//! Generated from the issue table by scripts/contract.ts. Do not edit.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IssueCode {
${entries.map(([code]) => `${pascal(code)},`).join("\n")}
}

impl IssueCode {
pub fn as_str(&self) -> &'static str {
match self {
${arms((code) => quote(code))}
}
}

pub fn template(&self) -> &'static str {
match self {
${arms((_code, template) => quote(template))}
}
}
}
`;
}

const versionRust = (): string =>
	`//! Generated by scripts/contract.ts. Do not edit.\n\npub const CONTRACT_VERSION: &str = ${JSON.stringify(CONTRACT_VERSION)};\n`;

