import type { CaseSource } from "../caseAdapter";

const pattern = (source: string, flags = "") => ({ source, flags });
const matches = (name: string, source: string, flags: string, texts: string[]): CaseSource => ({
	kind: "pattern.matches",
	name,
	input: { source, flags, texts },
});
const finds = (name: string, source: string, flags: string, text: string, froms: number[]): CaseSource => ({
	kind: "pattern.find",
	name,
	input: { source, flags, text, froms },
});
const edits = (name: string, source: string, flags: string, template: string, texts: string[]): CaseSource => ({
	kind: "pattern.edits",
	name,
	input: { source, flags, template, texts },
});

