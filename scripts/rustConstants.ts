// Writes Rust constants from TypeScript values.

import { quote } from "@nyaaai/testkit/rustNames";

////////////////////////////////
//  Functions & Helpers

const doc = (about: string | undefined): string => (about ? `/// ${about}\n` : "");

/** `pub const NAME: &str = "text";` */
export function rustText(name: string, value: string, about?: string): string {
	return `${doc(about)}pub const ${name}: &str = ${quote(value)};\n`;
}

/** `pub const NAME: type = 1;` for a whole number of an unsigned type. */
export function rustWhole(name: string, type: "u8" | "u32" | "u64" | "usize", value: number, about?: string): string {
	if (!Number.isSafeInteger(value) || value < 0) throw new Error(`${name} is not a whole number: ${value}`);
	return `${doc(about)}pub const ${name}: ${type} = ${value};\n`;
}

/** `pub const NAME: [&str; N] = [..];`, in the order given. */
export function rustTexts(name: string, values: Iterable<string>, about?: string): string {
	const held = [...values];
	return `${doc(about)}pub const ${name}: [&str; ${held.length}] = [${held.map(quote).join(", ")}];\n`;
}

/** A whole generated module. */
export function rustModule(about: string, constants: string[]): string {
	return `//! ${about} Generated by scripts/contract.ts. Do not edit.\n\n${constants.join("\n")}`;
}
