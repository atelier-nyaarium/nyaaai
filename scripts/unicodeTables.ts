// Generates the NFC tables from Unicode 17.0.
// Run: bun scripts/unicodeTables.ts <ucd folder>

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const VERSION = "17.0.0";

interface Tables {
	ccc: number[];
	decomp: number[];
	compose: number[];
}

/** Reads a code point from a UCD field. */
function codePoint(text: string): number {
	return Number.parseInt(text, 16);
}

/** Semicolon fields of one UnicodeData.txt line. */
function fieldsOf(line: string): string[] {
	return line.split(";");
}

/** Canonical decomposition, skipped when absent or compatibility. */
function decompOf(line: string): number[] | undefined {
	const field = fieldsOf(line)[5] ?? "";
	if (field === "" || field.startsWith("<")) return undefined;
	const parts = field.split(" ").map(codePoint);
	if (parts.length > 2) throw new Error(`canonical decomposition of ${parts.length} code points`);
	return parts;
}

function buildTables(folder: string): Tables {
	const ccc = new Map<number, number>();
	const decomp: number[] = [];
	const rows = readFileSync(path.join(folder, "UnicodeData.txt"), "utf8").split("\n");
	for (const line of rows) {
		if (line === "") continue;
		const fields = fieldsOf(line);
		const cp = codePoint(fields[0]!);
		const class_ = Number.parseInt(fields[3]!, 10);
		if (class_ !== 0) ccc.set(cp, class_);
		const parts = decompOf(line);
		if (parts === undefined) continue;
		decomp.push(cp, parts[0]!, parts.length === 2 ? parts[1]! : 0);
	}

	const excluded = new Set<number>();
	const exclusionRows = readFileSync(path.join(folder, "CompositionExclusions.txt"), "utf8").split("\n");
	for (const line of exclusionRows) {
		const hash = line.indexOf("#");
		const held = (hash === -1 ? line : line.slice(0, hash)).trim();
		if (held !== "") excluded.add(codePoint(held));
	}

	const pairs: Array<[number, number, number]> = [];
	for (let at = 0; at < decomp.length; at += 3) {
		const cp = decomp[at]!;
		const first = decomp[at + 1]!;
		const second = decomp[at + 2]!;
		if (second === 0 || excluded.has(cp)) continue;
		if ((ccc.get(first) ?? 0) !== 0) continue;
		pairs.push([first, second, cp]);
	}
	pairs.sort((left, right) => (left[0] !== right[0] ? left[0] - right[0] : left[1] - right[1]));
	const compose: number[] = pairs.flat();

	const cccPacked = [...ccc.entries()].map(([cp, class_]) => (cp << 8) | class_).sort((left, right) => left - right);

	return { ccc: cccPacked, decomp, compose };
}

/** Packs numbers onto fixed-width lines. */
function linesOf(numbers: number[], perLine: number, indent: string): string {
	const held: string[] = [];
	for (let at = 0; at < numbers.length; at += perLine) {
		held.push(`${indent}${numbers.slice(at, at + perLine).join(", ")}`);
	}
	return held.join(",\n");
}

function typescript(tables: Tables): string {
	const pack = (numbers: number[]): string => linesOf(numbers, 16, "\t");
	return `// Generated by scripts/unicodeTables.ts from Unicode 17.0. Do not edit.

export const UNICODE_VERSION = "${VERSION}";

/** Packed combining classes: \`(code point << 8) | class\`, sorted. */
// biome-ignore format: generated tables
export const CCC: number[] = [
${pack(tables.ccc)},
];

/** Canonical decompositions: [code point, first, second] triples, sorted. */
// biome-ignore format: generated tables
export const DECOMP: number[] = [
${pack(tables.decomp)},
];

/** Composition pairs: [first, second, composite] triples, sorted. */
// biome-ignore format: generated tables
export const COMPOSE: number[] = [
${pack(tables.compose)},
];
`;
}

function rust(tables: Tables): string {
	const pack = (numbers: number[]): string => linesOf(numbers, 16, "    ");
	return `//! Generated by scripts/unicodeTables.ts from Unicode 17.0. Do not edit.

pub const UNICODE_VERSION: &str = "${VERSION}";

/// Packed combining classes: \`(code point << 8) | class\`, sorted.
#[rustfmt::skip]
pub static CCC: &[u32] = &[
${pack(tables.ccc)},
];

/// Canonical decompositions: [code point, first, second] triples, sorted.
#[rustfmt::skip]
pub static DECOMP: &[u32] = &[
${pack(tables.decomp)},
];

/// Composition pairs: [first, second, composite] triples, sorted.
#[rustfmt::skip]
pub static COMPOSE: &[u32] = &[
${pack(tables.compose)},
];
`;
}

if (import.meta.main) {
	const [folder] = process.argv.slice(2);
	if (!folder) {
		console.error("usage: bun scripts/unicodeTables.ts <ucd folder>");
		process.exit(1);
	}
	const tables = buildTables(folder);
	const out = path.join(import.meta.dirname, "..");
	writeFileSync(path.join(out, "ts", "contract", "src", "nfcTables.ts"), typescript(tables));
	writeFileSync(path.join(out, "rust", "contract", "src", "nfc_tables.rs"), rust(tables));
	console.log(`ccc: ${tables.ccc.length} entries`);
	console.log(`decomp: ${tables.decomp.length / 3} entries`);
	console.log(`compose: ${tables.compose.length / 3} entries`);
}
