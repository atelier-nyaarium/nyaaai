// Contract tests.

import { afterAll, beforeAll, describe, expect, it } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import type { Json, SetSchema } from "@nyaaai/contract/schemaExport";
import { shapeSets } from "@nyaaai/contract/shape";
import { kindsOf } from "@nyaaai/testkit/caseGroup";
import type { RustTarget } from "@nyaaai/testkit/project";
import { runCase } from "../caseAdapter";
import { contractCases } from "../caseSources/contract";
import { sourcesOf } from "../cases";
import { drift } from "../contract";
import { formProblems, irOf } from "../contract/ir";
import { emitRust } from "../contract/rust";
import { loadProject, PROJECT_ROOT } from "../project";

////////////////////////////////
//  Functions & Helpers

let temp: string;

const doc = ($defs: Record<string, Json>): SetSchema => ({
	$schema: "https://json-schema.org/draft/2020-12/schema",
	$id: "t.output.json",
	"x-contract-version": "0.0.0",
	$defs,
});

const object = (properties: Record<string, Json>, extra: Record<string, Json> = {}): Json => ({
	type: "object",
	properties,
	required: Object.keys(properties),
	additionalProperties: false,
	...extra,
});

const target = (set: string, crate = "nyaaai_contract"): [string, RustTarget] => [
	set,
	{ crate, module: `shapes::${set}`, file: `${set}.rs` },
];

const TARGETS = new Map([target("t")]);

function rustOf($defs: Record<string, Json>): string {
	const sets = irOf(new Map([["t", doc($defs)]]));
	return emitRust(sets.get("t") as never, sets, TARGETS);
}

const tuple = (...places: Json[]): Json => ({
	type: "array",
	prefixItems: places,
	items: false,
	minItems: places.length,
	maxItems: places.length,
});

/** Mutually recursive sets. */
function crossed(crate: string): string {
	const held = (other: string, name: string): Json =>
		object({ next: { anyOf: [{ $ref: `${other}.output.json#/$defs/${name}` }, { type: "null" }] } });
	const sets = irOf(
		new Map([
			["a", doc({ A: held("b", "B") })],
			["b", doc({ B: held("a", "A") })],
		]),
	);
	return emitRust(sets.get("a") as never, sets, new Map([target("a"), target("b", crate)]));
}

const failure = (run: () => unknown): string => {
	try {
		run();
	} catch (error) {
		return error instanceof Error ? error.message : String(error);
	}
	return "";
};

////////////////////////////////
//  Tests

beforeAll(() => {
	temp = mkdtempSync(path.join(tmpdir(), "nyaaai-contract-"));
});

afterAll(() => {
	rmSync(temp, { recursive: true, force: true });
});

describe("the contract generator", () => {
	it("names a generated file that is missing, stale or no longer generated", () => {
		const fresh = new Map([
			["schema/a.output.json", "new"],
			["rust/a.rs", "new"],
		]);
		writeFileSync(
			path.join(temp, "parity.generated.json"),
			`${JSON.stringify({ contract: ["schema/gone.output.json"] })}\n`,
		);
		mkdirSync(path.join(temp, "schema"));
		writeFileSync(path.join(temp, "schema", "a.output.json"), "old");
		expect(drift(temp, fresh)).toEqual([
			"schema/a.output.json differs from a fresh run",
			"rust/a.rs is not written",
			"schema/gone.output.json is generated by nothing",
			"parity.generated.json is stale",
		]);
		writeFileSync(path.join(temp, "schema", "a.output.json"), "new");
		mkdirSync(path.join(temp, "rust"));
		writeFileSync(path.join(temp, "rust", "a.rs"), "new");
		writeFileSync(
			path.join(temp, "parity.generated.json"),
			`${JSON.stringify({ contract: ["rust/a.rs", "schema/a.output.json"] })}\n`,
		);
		expect(drift(temp, fresh)).toEqual([]);
	});

	it("holds a round-trip case for every named shape", () => {
		const cased = new Set(
			contractCases.map(({ input }) => {
				const { set, shape } = input as { set: string; shape: string };
				return `${set}.${shape}`;
			}),
		);
		// Runner-owned shapes.
		const named = shapeSets()
			.filter((set) => set.name !== "cases" && set.name !== "caseFile")
			.flatMap((set) => Object.keys(set.shapes).map((shape) => `${set.name}.${shape}`));
		expect(named.filter((name) => !cased.has(name))).toEqual([]);
	});

	it("holds a case for every function kind", async () => {
		const project = await loadProject();
		const cased = new Set(sourcesOf(project).map((source) => source.kind));
		expect([...kindsOf(project.groups).keys()].filter((kind) => !cased.has(kind))).toEqual([]);
	});

	it("marks the project root only for a kind with a context", async () => {
		const project = await loadProject();
		const plain = await runCase(project, "js.string", { texts: [JSON.stringify(PROJECT_ROOT)] });
		expect(plain).toEqual({ strings: [PROJECT_ROOT] });
		const handed = JSON.stringify(await runCase(project, "testkit.context", { folder: "a" }));
		expect([handed.includes(PROJECT_ROOT), handed.includes("$ROOT")]).toEqual([false, true]);
	});

	it("refuses a schema outside the dialect", () => {
		const outside: Array<Record<string, Json>> = [
			{ A: { type: "string", pattern: "^a" } },
			{ A: { type: "string", format: "uri" } },
			{ A: { type: "array", prefixItems: [{ type: "string" }] } },
			{ A: { type: "array", prefixItems: [{ type: "string" }], items: false, minItems: 0, maxItems: 1 } },
			{ A: { type: "array", prefixItems: [], items: false, minItems: 0, maxItems: 0 } },
			{ A: { type: "integer", "x-hooks": [{ kind: "match", source: "^a", flags: "" }] } },
			{ A: { type: "object", properties: {}, required: [] } },
			{ A: { type: "object", propertyNames: { enum: ["a"] }, additionalProperties: {} } },
			{ A: object({ a: { type: "string", default: "x" } }, { required: [] }) },
			{ A: { oneOf: [{ $ref: "#/$defs/B" }] }, B: object({ kind: { type: "string", const: "b" } }) },
			{ A: { oneOf: [{ $ref: "#/$defs/B" }], "x-tag": "kind" }, B: object({ kind: { type: "string" } }) },
			{ A: { $ref: "#/$defs/Missing" } },
		];
		for (const $defs of outside) {
			expect(failure(() => rustOf($defs))).not.toBe("");
		}
	});

	it("lets the two forms differ by defaults alone", () => {
		const output = doc({ A: object({ a: { type: "string", default: "x" }, b: { type: "number" } }) });
		const input = doc({
			A: {
				type: "object",
				properties: { a: { type: "string", default: "x" }, b: { type: "number" } },
				required: ["b"],
			},
		});
		expect(formProblems("t", input, output)).toEqual([]);
		const piped = doc({
			A: { type: "object", properties: { a: { type: "number" }, b: { type: "number" } }, required: ["b"] },
		});
		expect(formProblems("t", piped, output)).toHaveLength(1);
	});

	it("refuses two names that become one in Rust", () => {
		const clashes: Array<Record<string, Json>> = [
			{ A: object({ maxSize: { type: "string" }, max_size: { type: "string" } }) },
			{ A: { type: "string", enum: ["no-rows", "no_rows"] } },
			{ A: object({ inner: object({}) }), AInner: object({}) },
			{ lower: { type: "string" } },
		];
		for (const $defs of clashes) {
			expect(failure(() => rustOf($defs))).not.toBe("");
		}
	});

	it("gives each hook one Rust function with one use", () => {
		const hooked = (type: string, ...hooks: Json[]): Json => ({ type, "x-hooks": hooks });
		const check = (name: string): Json => ({ kind: "refine", name });
		const shared = rustOf({ A: hooked("string", check("isShort")), B: hooked("string", check("isShort")) });
		expect(shared).toContain("hooks::is_short");
		const clashes: Array<Record<string, Json>> = [
			{ A: hooked("string", check("isShort")), B: hooked("string", check("is_short")) },
			{ A: hooked("string", check("isShort")), B: hooked("number", check("isShort")) },
			{ A: hooked("string", check("fix")), B: hooked("string", { kind: "preprocess", name: "fix" }) },
		];
		for (const $defs of clashes) {
			expect(failure(() => rustOf($defs))).not.toBe("");
		}
	});

	it("checks text against a pattern compiled once", () => {
		const pattern = (message?: string): Json => ({
			kind: "match",
			source: "^a\\d",
			flags: "i",
			...(message ? { message } : {}),
		});
		const rust = rustOf({
			A: { type: "string", "x-hooks": [pattern()] },
			B: { type: "string", "x-hooks": [pattern("Starts with a.")] },
		});
		expect(rust.match(/LazyLock::new/g)).toHaveLength(1);
		expect(rust).toContain('Pattern::compile("^a\\\\d", "i")');
		expect(rust).toContain('Some("Starts with a.")');
	});

	it("boxes a reference that would hold itself by value", () => {
		const rust = rustOf({
			Chain: object({ next: { anyOf: [{ $ref: "#/$defs/Chain" }, { type: "null" }] } }),
			Tree: object({ kids: { type: "array", items: { $ref: "#/$defs/Tree" } } }),
		});
		expect(rust).toContain("pub next: Option<Box<Chain>>");
		expect(rust).toContain("pub kids: Vec<Tree>");
		const paired = rustOf({
			Pair: object({ rest: { anyOf: [tuple({ $ref: "#/$defs/Pair" }), { type: "null" }] } }),
		});
		expect(paired).toContain("pub rest: Option<(Box<Pair>,)>");
	});

	it("refuses a type alias that names itself", () => {
		const list = (name: string): Json => ({ type: "array", items: { $ref: `#/$defs/${name}` } });
		expect(failure(() => rustOf({ List: list("List") }))).toContain("wrap");
		const through = { A: tuple({ anyOf: [{ $ref: "#/$defs/B" }, { type: "null" }] }), B: list("A") };
		expect(failure(() => rustOf(through))).toContain("wrap");
		// A struct on the way is a type of its own.
		const rust = rustOf({ Node: object({ kids: { $ref: "#/$defs/Kids" } }), Kids: list("Node") });
		expect(rust).toContain("pub type Kids = Vec<Node>;");
	});

	it("imports the trait a set of aliases calls", () => {
		const sets = irOf(
			new Map([
				["a", doc({ Leaf: object({ x: { type: "string" } }) })],
				["b", doc({ List: { type: "array", items: { $ref: "a.output.json#/$defs/Leaf" } } })],
			]),
		);
		const rust = emitRust(sets.get("b") as never, sets, new Map([target("a"), target("b")]));
		expect(rust).toContain("shape::{self, Path, Refused, Shape}");
	});

	it("boxes a cycle across sets and refuses one across crates", () => {
		expect(crossed("nyaaai_contract")).toContain("pub next: Option<Box<crate::shapes::b::B>>");
		expect(failure(() => crossed("other_crate"))).toContain("crosses crates");
	});
});
