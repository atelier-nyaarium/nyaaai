#[test]
fn a_rule_reads_as_the_c_library_does() {
    assert!(ROWS.len() >= 60, "{}", ROWS.len());
    let mut wrong = Vec::new();
    for (rule, at, east) in ROWS {
        let zone = Zone::from_posix(rule).unwrap();
        // Whole minutes, a second's half rounded up.
        let wanted = (east + 30).div_euclid(60);
        for ms in [at * 1000, at * 1000 + 999] {
            let got = zone.offset_minutes(ms);
            if got != wanted {
                wrong.push(format!("{rule} at {at}: {got}, wanted {wanted}"));
            }
        }
    }
    assert_eq!(wrong, Vec::<String>::new());
}
